#!/usr/bin/env node
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { execFileSync, spawnSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const INTEL_TRANSFORMERS_ENTRY = 'transformers.clementine-wasm.mjs';

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const DESKTOP_DIR = path.resolve(SCRIPT_DIR, '..');
const ROOT_DIR = path.resolve(DESKTOP_DIR, '..', '..');

function replaceExactlyOnce(source, needle, replacement) {
  const first = source.indexOf(needle);
  if (first < 0 || source.indexOf(needle, first + needle.length) >= 0) {
    throw new Error('upstream Transformers bundle changed; refusing to create an unverified Intel WASM adapter');
  }
  return source.slice(0, first) + replacement + source.slice(first + needle.length);
}

/**
 * Transformers.js selects onnxruntime-node whenever it detects Node. ONNX
 * Runtime 1.24 no longer publishes an Intel-macOS Node binding, while the same
 * Transformers package ships an architecture-neutral WASM runtime. Create a
 * separate, packaging-only entry instead of modifying the canonical module:
 * x64 loads WASM, keeps the Node filesystem cache, and supplies model bytes
 * (the WASM backend cannot open a filesystem path directly).
 */
export function patchTransformersNodeForWasm(source) {
  let patched = replaceExactlyOnce(
    source,
    'import * as ONNX_NODE from "onnxruntime-node";',
    // The package's Node entry embeds a filesystem-safe WASM loader. The
    // `/wasm` browser entry tries to fetch a file: URL under Node and fails.
    'import * as ONNX_NODE from "onnxruntime-web";',
  );
  patched = replaceExactlyOnce(
    patched,
    '  supportedDevices.push("webgpu");\n  supportedDevices.push("cpu");\n  defaultDevices = ["cpu"];',
    '  supportedDevices.push("webgpu");\n  supportedDevices.push("wasm");\n  defaultDevices = ["wasm"];',
  );
  patched = replaceExactlyOnce(
    patched,
    'return await getModelFile(pretrained_model_name_or_path, fullPath, true, options, apis.IS_NODE_ENV);',
    'return await getModelFile(pretrained_model_name_or_path, fullPath, true, options, false);',
  );
  return `// Generated by Clementine's fail-closed Intel macOS packaging hook.\n${patched}`;
}

function readJson(file) {
  return JSON.parse(readFileSync(file, 'utf8'));
}

function nativeFiles(dir) {
  if (!existsSync(dir)) return [];
  const out = [];
  const visit = (current) => {
    for (const entry of readdirSync(current, { withFileTypes: true })) {
      const full = path.join(current, entry.name);
      if (entry.isDirectory()) visit(full);
      else if (/\.(?:node|dylib|native)$/.test(entry.name)) out.push(full);
    }
  };
  visit(dir);
  return out;
}

export function assertMachOArchitecture(file, expectedArch) {
  const description = execFileSync('/usr/bin/file', [file], { encoding: 'utf8' }).trim();
  if (!description.includes('Mach-O') || !description.includes(expectedArch)) {
    throw new Error(`${file} is not a Mach-O containing ${expectedArch}: ${description}`);
  }
}

function targetSharpPackages(arch) {
  const suffix = arch === 'arm64' ? 'arm64' : 'x64';
  return [
    `sharp-darwin-${suffix}`,
    `sharp-libvips-darwin-${suffix}`,
  ];
}

function assertPackageVersion(packageDir, expectedVersion) {
  const manifest = path.join(packageDir, 'package.json');
  if (!existsSync(manifest)) throw new Error(`required native package is missing: ${packageDir}`);
  const actual = readJson(manifest).version;
  if (actual !== expectedVersion) {
    throw new Error(`native package ${path.basename(packageDir)} ${actual} != locked ${expectedVersion}`);
  }
}

function verifySharp(daemonModules, arch, inspectBinary) {
  const sharpManifest = readJson(path.join(daemonModules, 'sharp', 'package.json'));
  const imgDir = path.join(daemonModules, '@img');
  const expectedArch = arch === 'arm64' ? 'arm64' : 'x86_64';
  const wanted = new Set(targetSharpPackages(arch));

  for (const name of readdirSync(imgDir, { withFileTypes: true })) {
    if (
      name.isDirectory()
      && /^(?:sharp|sharp-libvips)-darwin-(?:arm64|x64)$/.test(name.name)
      && !wanted.has(name.name)
    ) {
      throw new Error(`wrong-architecture Sharp package leaked into ${arch} app: ${name.name}`);
    }
  }

  for (const name of wanted) {
    const packageDir = path.join(imgDir, name);
    const expectedVersion = sharpManifest.optionalDependencies?.[`@img/${name}`];
    if (!expectedVersion) throw new Error(`sharp does not declare @img/${name}`);
    assertPackageVersion(packageDir, expectedVersion);
    const binaries = nativeFiles(packageDir);
    if (binaries.length === 0) throw new Error(`native payload is missing from @img/${name}`);
    for (const binary of binaries) inspectBinary(binary, expectedArch);
  }
}

function verifyOnnx(daemonModules, arch, inspectBinary) {
  const nativeRoot = path.join(daemonModules, 'onnxruntime-node');
  const wasmRoot = path.join(daemonModules, 'onnxruntime-web', 'dist');
  const transformersDist = path.join(daemonModules, '@huggingface', 'transformers', 'dist');

  if (arch === 'x64') {
    if (existsSync(nativeRoot)) {
      throw new Error('Intel app contains onnxruntime-node even though upstream publishes only ARM64 for macOS');
    }
    const wasmFile = path.join(wasmRoot, 'ort-wasm-simd-threaded.wasm');
    if (!existsSync(wasmFile)) throw new Error('Intel app is missing the architecture-neutral ONNX WASM runtime');
    const adapter = path.join(transformersDist, INTEL_TRANSFORMERS_ENTRY);
    if (!existsSync(adapter)) throw new Error(`Intel Transformers WASM adapter is missing: ${adapter}`);
    const adapterText = readFileSync(adapter, 'utf8');
    if (!adapterText.includes('from "onnxruntime-web"') || adapterText.includes('from "onnxruntime-node"')) {
      throw new Error('Intel Transformers WASM adapter did not remove the native ONNX import');
    }
    return;
  }

  const darwinRoot = path.join(nativeRoot, 'bin', 'napi-v6', 'darwin');
  if (existsSync(path.join(darwinRoot, 'x64'))) {
    throw new Error('x64 ONNX payload leaked into the arm64 app');
  }
  const armRoot = path.join(darwinRoot, 'arm64');
  const binaries = nativeFiles(armRoot);
  if (binaries.length < 2) throw new Error('arm64 ONNX binding/shared library payload is incomplete');
  for (const binary of binaries) inspectBinary(binary, 'arm64');
}

export function verifyPackagedMacDaemon({
  daemonDir,
  arch,
  inspectBinary = assertMachOArchitecture,
}) {
  if (arch !== 'arm64' && arch !== 'x64') throw new Error(`unsupported macOS architecture: ${arch}`);
  const daemonModules = path.join(daemonDir, 'node_modules');
  const expectedArch = arch === 'arm64' ? 'arm64' : 'x86_64';
  const sqliteRoot = path.join(daemonModules, 'better-sqlite3');
  const sqlite = path.join(sqliteRoot, 'build', 'Release', 'better_sqlite3.node');
  if (!existsSync(sqlite)) throw new Error(`packaged better-sqlite3 is missing: ${sqlite}`);
  const sqliteBinaries = nativeFiles(sqliteRoot);
  if (sqliteBinaries.length === 0) throw new Error('packaged better-sqlite3 has no native payload');
  for (const binary of sqliteBinaries) inspectBinary(binary, expectedArch);
  verifySharp(daemonModules, arch, inspectBinary);
  verifyOnnx(daemonModules, arch, inspectBinary);
}

export function preparePackagedMacDaemon({
  daemonDir,
  arch,
  stageDir,
  inspectBinary = assertMachOArchitecture,
}) {
  if (arch !== 'arm64' && arch !== 'x64') throw new Error(`unsupported macOS architecture: ${arch}`);
  const daemonModules = path.join(daemonDir, 'node_modules');
  const imgDir = path.join(daemonModules, '@img');
  mkdirSync(imgDir, { recursive: true });

  // electron-rebuild writes the target ABI/architecture to build/Release.
  // The npm package can also carry a host-architecture prebuild under bin/;
  // it is redundant and must not leak ARM64 into the Intel artifact.
  rmSync(path.join(daemonModules, 'better-sqlite3', 'bin'), { recursive: true, force: true });

  const keep = new Set(targetSharpPackages(arch));
  for (const name of ['sharp-darwin-arm64', 'sharp-darwin-x64', 'sharp-libvips-darwin-arm64', 'sharp-libvips-darwin-x64']) {
    if (!keep.has(name)) rmSync(path.join(imgDir, name), { recursive: true, force: true });
  }

  const transformersDist = path.join(daemonModules, '@huggingface', 'transformers', 'dist');
  const generatedAdapter = path.join(transformersDist, INTEL_TRANSFORMERS_ENTRY);
  if (arch === 'x64') {
    if (!stageDir) throw new Error('CLEMENTINE_MAC_NATIVE_STAGE is required for the x64 package');
    for (const name of keep) {
      const source = path.join(stageDir, 'node_modules', '@img', name);
      if (!existsSync(source)) throw new Error(`staged x64 native package is missing: ${source}`);
      cpSync(source, path.join(imgDir, name), { recursive: true, force: true });
    }

    // Upstream ORT 1.24.1+ intentionally stopped publishing macOS x86_64.
    // Never leave its ARM64-only payload inside an Intel app.
    rmSync(path.join(daemonModules, 'onnxruntime-node'), { recursive: true, force: true });

    const sourceEntry = path.join(transformersDist, 'transformers.node.mjs');
    const patched = patchTransformersNodeForWasm(readFileSync(sourceEntry, 'utf8'));
    writeFileSync(generatedAdapter, patched, 'utf8');
  } else {
    rmSync(generatedAdapter, { force: true });
    rmSync(path.join(daemonModules, 'onnxruntime-node', 'bin', 'napi-v6', 'darwin', 'x64'), {
      recursive: true,
      force: true,
    });
  }

  verifyPackagedMacDaemon({ daemonDir, arch, inspectBinary });
}

export function stageIntelSharp({ stageDir, rootDir = ROOT_DIR }) {
  const sharpManifest = readJson(path.join(rootDir, 'node_modules', 'sharp', 'package.json'));
  const packageNames = ['@img/sharp-darwin-x64', '@img/sharp-libvips-darwin-x64'];
  const specs = packageNames.map((name) => {
    const version = sharpManifest.optionalDependencies?.[name];
    if (!version) throw new Error(`sharp does not declare ${name}`);
    return `${name}@${version}`;
  });

  mkdirSync(stageDir, { recursive: true });
  rmSync(path.join(stageDir, 'node_modules'), { recursive: true, force: true });
  rmSync(path.join(stageDir, 'package-lock.json'), { force: true });
  writeFileSync(path.join(stageDir, 'package.json'), '{"private":true}', 'utf8');
  const cacheDir = path.join(stageDir, '.npm-cache');
  const result = spawnSync(
    process.platform === 'win32' ? 'npm.cmd' : 'npm',
    [
      'install',
      '--ignore-scripts',
      '--no-audit',
      '--no-fund',
      '--no-save',
      '--package-lock=false',
      '--cpu=x64',
      '--os=darwin',
      '--force',
      ...specs,
    ],
    {
      cwd: stageDir,
      env: { ...process.env, npm_config_cache: cacheDir },
      stdio: 'inherit',
    },
  );
  if (result.status !== 0) throw new Error(`failed to stage Intel Sharp packages (npm status ${result.status})`);

  for (const [name, spec] of packageNames.map((name, index) => [name, specs[index]])) {
    const packageDir = path.join(stageDir, 'node_modules', ...name.split('/'));
    assertPackageVersion(packageDir, spec.slice(spec.lastIndexOf('@') + 1));
    const binaries = nativeFiles(packageDir);
    if (binaries.length === 0) throw new Error(`staged package has no native payload: ${name}`);
    for (const binary of binaries) assertMachOArchitecture(binary, 'x86_64');
  }
}

function argValue(name) {
  const index = process.argv.indexOf(name);
  return index >= 0 ? process.argv[index + 1] : undefined;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const command = process.argv[2];
  if (command === 'stage-x64') {
    const stageDir = argValue('--stage');
    if (!stageDir) throw new Error('--stage is required');
    stageIntelSharp({ stageDir, rootDir: argValue('--root') ?? ROOT_DIR });
  } else if (command === 'verify') {
    const daemonDir = argValue('--daemon');
    const arch = argValue('--arch');
    if (!daemonDir || !arch) throw new Error('--daemon and --arch are required');
    verifyPackagedMacDaemon({ daemonDir, arch });
  } else {
    throw new Error(`usage: mac-native-deps.mjs stage-x64|verify`);
  }
}
